    [Serializable]
    public sealed class StoreOperationReport
    {
        [SerializeField] private bool succeeded;
        [SerializeField] private List<StoreValidationIssue> issues = new List<StoreValidationIssue>();
        [SerializeField] private string outputPath = string.Empty;
        [SerializeField] private string logPath = string.Empty;

        public bool Succeeded
        {
            get => succeeded;
            set => succeeded = value;
        }

        public List<StoreValidationIssue> Issues
        {
            get
            {
                if (issues == null)
                {
                    issues = new List<StoreValidationIssue>();
                }

                return issues;
            }
            set => issues = value ?? new List<StoreValidationIssue>();
        }

        public string OutputPath
        {
            get => outputPath;
            set => outputPath = value ?? string.Empty;
        }

        public string LogPath
        {
            get => logPath;
            set => logPath = value ?? string.Empty;
        }

        public void AddIssue(StoreValidationIssue issue)
        {
            if (issue == null)
            {
                return;
            }

            Issues.Add(issue);
            if (issue.Severity == StoreValidationSeverity.Error)
            {
                succeeded = false;
            }
        }

        public static StoreOperationReport Success(string outputPath = "", string logPath = "")
        {
            return new StoreOperationReport
            {
                Succeeded = true,
                OutputPath = outputPath,
                LogPath = logPath
            };
        }

        public static StoreOperationReport Failure(string code, string message)
        {
            var report = new StoreOperationReport { Succeeded = false };
            report.AddIssue(new StoreValidationIssue(StoreValidationSeverity.Error, code, message));
            return report;
        }
    }
