    public enum StorePlatform
    {
        None = 0,
        Steam = 1,
        Epic = 2
    }

    public enum StoreReleaseChannel
    {
        Development = 0,
        Stage = 1,
        Live = 2
    }

    public enum StoreValidationSeverity
    {
        Info = 0,
        Warning = 1,
        Error = 2
    }

    [Serializable]
    public sealed class StoreValidationIssue
    {
        [SerializeField] private StoreValidationSeverity severity;
        [SerializeField] private string code = string.Empty;
        [SerializeField] private string message = string.Empty;
        [SerializeField] private string context = string.Empty;

        public StoreValidationIssue()
        {
        }

        public StoreValidationIssue(
            StoreValidationSeverity severity,
            string code,
            string message,
            string context = "")
        {
            this.severity = severity;
            this.code = code ?? string.Empty;
            this.message = message ?? string.Empty;
            this.context = context ?? string.Empty;
        }

        public StoreValidationSeverity Severity
        {
            get => severity;
            set => severity = value;
        }

        public string Code
        {
            get => code;
            set => code = value ?? string.Empty;
        }

        public string Message
        {
            get => message;
            set => message = value ?? string.Empty;
        }

        public string Context
        {
            get => context;
            set => context = value ?? string.Empty;
        }

        public override string ToString()
        {
            return string.IsNullOrWhiteSpace(context)
                ? $"[{severity}] {code}: {message}"
                : $"[{severity}] {code}: {message} ({context})";
        }
    }

